// Package caddyfile renders one app's Caddy site blocks and reads them back.
package caddyfile

import (
	"fmt"
	"strings"

	"github.com/sparkstonepdx/nook/internal/notfound"
	"github.com/sparkstonepdx/nook/internal/redirects"
)

// A static site's misses get its own 404.html, or else the server-wide one (package notfound).

// Site is one published hostname: a reverse proxy when Port > 0, otherwise static files from Root.
type Site struct {
	Host string
	Port int
	Root string
	// Folder and Version are recorded as a comment so `nook site deploy` can wait for its own deploy
	// (Version is the site folder's inode, which changes on every atomic swap).
	Folder  string
	Version string
	// CORS lets any origin read a static site's files (nook.json {"cors": true}).
	CORS bool
	// Rules are the static site's _redirects, in order.
	Rules []redirects.Rule
}

const redirectMark = " { # redirect"

// Render returns the generated file. Redirects maps www.<apex> to <apex>. ownCert, when set, says which hosts keep
// a certificate of their own even though a managed wildcard covers them (Caddy 2.10+ otherwise uses the wildcard,
// and serves nothing until it's issued).
func Render(source string, sites []Site, redirects [][2]string, ownCert func(host string) bool) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# generated by nook from %s: do not edit\n", source)
	for _, s := range sites {
		if s.Folder != "" {
			fmt.Fprintf(&b, "# site %s %s\n", s.Folder, s.Version)
		}
		if s.Port > 0 {
			fmt.Fprintf(&b, "%s {\n%s\treverse_proxy 127.0.0.1:%d\n}\n", s.Host, tlsLine(s.Host, ownCert), s.Port)
		} else {
			static(&b, s, tlsLine(s.Host, ownCert))
		}
	}
	for _, r := range redirects {
		fmt.Fprintf(&b, "%s%s\n%s\tredir https://%s{uri} permanent\n}\n", r[0], redirectMark, tlsLine(r[0], ownCert), r[1])
	}
	return b.String()
}

const serve = "file_server {\n\t\tprecompressed gzip\n\t}"

// static writes a static site's block. With _redirects rules, each is a handle in file order (Caddy keeps named
// matchers in the order written, and the first match wins, as on Netlify), then the usual files in a last handle.
// ForceAutomate is the line that keeps a host's own certificate under a wildcard.
const ForceAutomate = "\ttls force_automate\n"

func tlsLine(host string, ownCert func(string) bool) string {
	if ownCert != nil && ownCert(host) {
		return ForceAutomate
	}
	return ""
}

func static(b *strings.Builder, s Site, tls string) {
	fmt.Fprintf(b, "%s {\n%s", s.Host, tls)
	if s.CORS {
		b.WriteString("\theader Access-Control-Allow-Origin *\n")
	}
	fmt.Fprintf(b, "\troot * %s\n", s.Root)
	// the rules file is settings, not content
	b.WriteString("\thandle /_redirects {\n\t\terror 404\n\t}\n")
	if len(s.Rules) == 0 {
		b.WriteString("\ttry_files {path} {path}/ /200.html\n\t" + serve + "\n")
	} else {
		for i, r := range s.Rules {
			m := fmt.Sprintf("nook_r%d", i)
			fmt.Fprintf(b, "\t@%s {\n\t\tpath_regexp %s `%s`\n", m, m, r.Regexp)
			if !r.Force {
				b.WriteString("\t\tnot file\n")
			}
			fmt.Fprintf(b, "\t}\n\thandle @%s {\n", m)
			if r.Redirect() {
				fmt.Fprintf(b, "\t\tredir %s %d\n", r.Target(m), r.Status)
			} else {
				fmt.Fprintf(b, "\t\trewrite * %s\n\t\t%s\n", r.Target(m), strings.ReplaceAll(serve, "\n", "\n\t"))
			}
			b.WriteString("\t}\n")
		}
		b.WriteString("\thandle {\n\t\ttry_files {path} {path}/ /200.html\n\t\t" + strings.ReplaceAll(serve, "\n", "\n\t") + "\n\t}\n")
	}
	fmt.Fprintf(b, "\thandle_errors {\n\t\t@own file /404.html\n\t\thandle @own {\n\t\t\trewrite * /404.html\n\t\t\tfile_server {\n\t\t\t\tprecompressed gzip\n\t\t\t}\n\t\t}\n\t\thandle {\n\t\t\troot * %s\n\t\t\trewrite * /404.html\n\t\t\tfile_server\n\t\t}\n\t}\n}\n", notfound.Dir)
}

// Hosts returns the hostnames a generated file serves for real, and the ones it only redirects.
func Hosts(text string) (live, redirects []string) {
	for _, line := range strings.Split(text, "\n") {
		switch {
		case strings.HasSuffix(line, redirectMark):
			redirects = append(redirects, strings.TrimSuffix(line, redirectMark))
		case strings.HasSuffix(line, " {") && !strings.HasPrefix(line, "\t") && !strings.HasPrefix(line, "#"):
			live = append(live, strings.TrimSuffix(line, " {"))
		}
	}
	return
}

// WithoutRedirect drops the automatic redirect block for host, if the file has one.
func WithoutRedirect(text, host string) (string, bool) {
	lines := strings.Split(text, "\n")
	var out []string
	skip, found := false, false
	for _, l := range lines {
		if l == host+redirectMark {
			skip, found = true, true
			continue
		}
		if skip {
			if l == "}" {
				skip = false
			}
			continue
		}
		out = append(out, l)
	}
	return strings.Join(out, "\n"), found
}

// Version returns the recorded version of a site folder, if the file has one.
func Version(text, folder string) string {
	for _, line := range strings.Split(text, "\n") {
		f := strings.Fields(line)
		if len(f) == 4 && f[0] == "#" && f[1] == "site" && f[2] == folder {
			return f[3]
		}
	}
	return ""
}
