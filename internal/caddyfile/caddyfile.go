// Package caddyfile renders one app's Caddy site blocks and reads them back.
package caddyfile

import (
	"fmt"
	"strings"

	"github.com/sparkstonepdx/nook/internal/config"
	"github.com/sparkstonepdx/nook/internal/notfound"
	"github.com/sparkstonepdx/nook/internal/redirects"
)

// A static site's misses get its own 404.html, or else the server-wide one (package notfound).

// Site is one published hostname: a reverse proxy when Port > 0, otherwise static files from Root.
type Site struct {
	Host string
	Port int
	Root string
	// Folder and Version are recorded as a comment so `nook site deploy` can wait for its own deploy
	// (Version is the site folder's inode, which changes on every atomic swap).
	Folder  string
	Version string
	// CORS lets any origin read a static site's files (nook.json {"cors": true}).
	CORS bool
	// TokenAuth (nook.json {"auth": "nook-token"}) sends each request past nook's token check first: no valid
	// deploy token, no request. The app gets X-Nook-App (which app's token it was) and never the token itself.
	TokenAuth bool
	// Open (nook.json "open") are paths that skip the token check, for callers that can't hold a token, like
	// browsers. Checked when nook.json is read: /, letters, digits, . _ ~ - and a trailing *.
	Open []string
	// Rules are the static site's _redirects, in order.
	Rules []redirects.Rule
	// Login, the app's name, puts the site behind nook's own login (the app's login switch on the dashboard):
	// every request goes past nook-web's login check first, which lets in a dashboard user allowed on the app,
	// or a deploy token as TokenAuth does. Dashboard is the dashboard's hostname, where people log in.
	Login     string
	Dashboard string
	// PostTo, for a static site, is the port of the provider that takes its POSTs (a form catcher, #98). The
	// provider gets the original path and X-Nook-Site (APP/HOST), which a client can't send its own of.
	PostTo int
	App    string
}

const redirectMark = " { # redirect"

// Render returns the generated file. Redirects maps www.<apex> to <apex>. ownCert, when set, says which hosts keep
// a certificate of their own even though a managed wildcard covers them (Caddy 2.10+ otherwise uses the wildcard,
// and serves nothing until it's issued).
func Render(source string, sites []Site, redirects [][2]string, ownCert func(host string) bool) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# generated by nook from %s: do not edit\n", source)
	for _, s := range sites {
		if s.Folder != "" {
			fmt.Fprintf(&b, "# site %s %s\n", s.Folder, s.Version)
		}
		if s.Login != "" {
			login(&b, s, tlsLine(s.Host, ownCert))
		} else if s.Port > 0 && s.TokenAuth && len(s.Open) > 0 {
			fmt.Fprintf(&b, "%s {\n%s\t@nook_open path %s\n\thandle @nook_open {\n\t\troute {\n\t\t\trequest_header -X-Nook-App\n\t\t\treverse_proxy 127.0.0.1:%d {\n\t\t\t\theader_up -Authorization\n%s\t\t\t}\n\t\t}\n\t}\n\thandle {\n%s\t}\n}\n",
				s.Host, tlsLine(s.Host, ownCert), strings.Join(s.Open, " "), s.Port, proxyOpts(4), indent(fmt.Sprintf(tokenAuth, TokenCheck, s.Port, proxyOpts(3))))
		} else if s.Port > 0 && s.TokenAuth {
			fmt.Fprintf(&b, "%s {\n%s"+tokenAuth+"}\n", s.Host, tlsLine(s.Host, ownCert), TokenCheck, s.Port, proxyOpts(3))
		} else if s.Port > 0 && StreamCloseDelay != "" {
			fmt.Fprintf(&b, "%s {\n%s\treverse_proxy 127.0.0.1:%d {\n%s\t}\n}\n", s.Host, tlsLine(s.Host, ownCert), s.Port, proxyOpts(2))
		} else if s.Port > 0 {
			fmt.Fprintf(&b, "%s {\n%s\treverse_proxy 127.0.0.1:%d\n}\n", s.Host, tlsLine(s.Host, ownCert), s.Port)
		} else {
			static(&b, s, tlsLine(s.Host, ownCert))
		}
	}
	for _, r := range redirects {
		fmt.Fprintf(&b, "%s%s\n%s\tredir https://%s{uri} permanent\n}\n", r[0], redirectMark, tlsLine(r[0], ownCert), r[1])
	}
	return b.String()
}

// StreamCloseDelay keeps websockets and other streams open this long after a config reload (Caddy 2.7+), so a
// deploy elsewhere doesn't drop every app's live connections. "" on an older Caddy, which would reject it.
var StreamCloseDelay = ""

// proxyOpts is the lines every app's reverse_proxy block gets, at the given depth of tabs.
func proxyOpts(tabs int) string {
	if StreamCloseDelay == "" {
		return ""
	}
	return strings.Repeat("\t", tabs) + "stream_close_delay " + StreamCloseDelay + "\n"
}

// SameConfig says whether two generated files differ only in their "# site" lines: those record each deploy's
// folder for `nook site deploy` to wait on, and Caddy ignores them, so a redeploy needs no reload.
func SameConfig(a, b string) bool { return withoutSiteLines(a) == withoutSiteLines(b) }

func withoutSiteLines(s string) string {
	var out []string
	for _, l := range strings.Split(s, "\n") {
		if !strings.HasPrefix(l, "# site ") {
			out = append(out, l)
		}
	}
	return strings.Join(out, "\n")
}

// TokenCheck is where Caddy asks nook-web whether a request's token is good (a var so tests can see it).
var TokenCheck = "unix/" + config.WebSocket

// tokenAuth runs in order (a route): a client's own X-Nook-App is dropped, nook-web checks the Bearer or Basic
// token and answers 204 with X-Nook-App or 401, and the app gets the request without the token.
const tokenAuth = `	route {
		request_header -X-Nook-App
		forward_auth %s {
			uri /api/v1/token-check
			copy_headers X-Nook-App
		}
		reverse_proxy 127.0.0.1:%d {
			header_up -Authorization
%s		}
	}
`

func indent(s string) string {
	return "\t" + strings.ReplaceAll(strings.TrimSuffix(s, "\n"), "\n", "\n\t") + "\n"
}

const serve = "file_server {\n\t\tprecompressed gzip\n\t}"

// static writes a static site's block. With _redirects rules, each is a handle in file order (Caddy keeps named
// matchers in the order written, and the first match wins, as on Netlify), then the usual files in a last handle.
// ForceAutomate is the line that keeps a host's own certificate under a wildcard.
const ForceAutomate = "\ttls force_automate\n"

func tlsLine(host string, ownCert func(string) bool) string {
	if ownCert != nil && ownCert(host) {
		return ForceAutomate
	}
	return ""
}

func static(b *strings.Builder, s Site, tls string) {
	fmt.Fprintf(b, "%s {\n%s", s.Host, tls)
	if s.CORS {
		b.WriteString("\theader Access-Control-Allow-Origin *\n")
	}
	b.WriteString(staticBody(s))
	b.WriteString(staticErrors())
}

// staticBody serves the files. Written in the order Caddy runs them, so it reads the same inside a route.
func staticBody(s Site) string {
	var b strings.Builder
	if s.PostTo > 0 {
		// try_files may have rewritten the path already (outside a route it runs first): send the original
		fmt.Fprintf(&b, "\t@nook_post method POST\n\thandle @nook_post {\n\t\trewrite * {http.request.orig_uri}\n\t\treverse_proxy 127.0.0.1:%d {\n\t\t\theader_up X-Nook-Site %s/%s\n%s\t\t}\n\t}\n",
			s.PostTo, s.App, s.Host, proxyOpts(3))
	}
	fmt.Fprintf(&b, "\troot * %s\n", s.Root)
	// the rules file is settings, not content
	b.WriteString("\thandle /_redirects {\n\t\terror 404\n\t}\n")
	if len(s.Rules) == 0 {
		b.WriteString("\ttry_files {path} {path}/ /200.html\n\t" + serve + "\n")
	} else {
		for i, r := range s.Rules {
			m := fmt.Sprintf("nook_r%d", i)
			fmt.Fprintf(&b, "\t@%s {\n\t\tpath_regexp %s `%s`\n", m, m, r.Regexp)
			if !r.Force {
				b.WriteString("\t\tnot file\n")
			}
			fmt.Fprintf(&b, "\t}\n\thandle @%s {\n", m)
			if r.Redirect() {
				fmt.Fprintf(&b, "\t\tredir %s %d\n", r.Target(m), r.Status)
			} else {
				fmt.Fprintf(&b, "\t\trewrite * %s\n\t\t%s\n", r.Target(m), strings.ReplaceAll(serve, "\n", "\n\t"))
			}
			b.WriteString("\t}\n")
		}
		b.WriteString("\thandle {\n\t\ttry_files {path} {path}/ /200.html\n\t\t" + strings.ReplaceAll(serve, "\n", "\n\t") + "\n\t}\n")
	}
	return b.String()
}

func staticErrors() string {
	return fmt.Sprintf("\thandle_errors {\n\t\t@own file /404.html\n\t\thandle @own {\n\t\t\trewrite * /404.html\n\t\t\tfile_server {\n\t\t\t\tprecompressed gzip\n\t\t\t}\n\t\t}\n\t\thandle {\n\t\t\troot * %s\n\t\t\trewrite * /404.html\n\t\t\tfile_server\n\t\t}\n\t}\n}\n", notfound.Dir)
}

// login writes a site behind nook's login. /.nook/* (the login hand-off and log out) goes to nook-web, told the
// dashboard's address (set here, so a client can't send its own); paths in
// Open skip the check; everything else runs in one route, in written order: the client's own X-Nook-App and
// X-Nook-User are dropped, nook-web answers 2xx with whichever applies (or sends the browser to log in), then
// the site is served. The upstream never sees X-Nook-Card, the key nook-web uses to read sites for their cards.
func login(b *strings.Builder, s Site, tls string) {
	fmt.Fprintf(b, "%s {\n%s", s.Host, tls)
	if s.CORS {
		b.WriteString("\theader Access-Control-Allow-Origin *\n")
	}
	fmt.Fprintf(b, "\thandle /.nook/* {\n\t\treverse_proxy %s {\n\t\t\theader_up X-Nook-Dash %s\n\t\t}\n\t}\n", TokenCheck, s.Dashboard)
	body := staticBody(s)
	if s.Port > 0 {
		body = fmt.Sprintf("\treverse_proxy 127.0.0.1:%d {\n\t\theader_up -X-Nook-Card\n", s.Port)
		if s.TokenAuth {
			body += "\t\theader_up -Authorization\n"
		}
		body += proxyOpts(2) + "\t}\n"
		if len(s.Open) > 0 {
			fmt.Fprintf(b, "\t@nook_open path %s\n\thandle @nook_open {\n\t\troute {\n\t\t\trequest_header -X-Nook-App\n\t\t\trequest_header -X-Nook-User\n%s\t\t}\n\t}\n",
				strings.Join(s.Open, " "), indent(indent(body)))
		}
	}
	fmt.Fprintf(b, "\thandle {\n\t\troute {\n\t\t\trequest_header -X-Nook-App\n\t\t\trequest_header -X-Nook-User\n"+
		"\t\t\tforward_auth %s {\n\t\t\t\turi /api/v1/login-check?app=%s&host=%s&dash=%s\n\t\t\t\tcopy_headers X-Nook-App X-Nook-User\n\t\t\t}\n%s\t\t}\n\t}\n",
		TokenCheck, s.Login, s.Host, s.Dashboard, indent(indent(body)))
	if s.Port > 0 {
		b.WriteString("}\n")
	} else {
		b.WriteString(staticErrors())
	}
}

// Hosts returns the hostnames a generated file serves for real, and the ones it only redirects.
func Hosts(text string) (live, redirects []string) {
	for _, line := range strings.Split(text, "\n") {
		switch {
		case strings.HasSuffix(line, redirectMark):
			redirects = append(redirects, strings.TrimSuffix(line, redirectMark))
		case strings.HasSuffix(line, " {") && !strings.HasPrefix(line, "\t") && !strings.HasPrefix(line, "#"):
			live = append(live, strings.TrimSuffix(line, " {"))
		}
	}
	return
}

// WithoutRedirect drops the automatic redirect block for host, if the file has one.
func WithoutRedirect(text, host string) (string, bool) {
	lines := strings.Split(text, "\n")
	var out []string
	skip, found := false, false
	for _, l := range lines {
		if l == host+redirectMark {
			skip, found = true, true
			continue
		}
		if skip {
			if l == "}" {
				skip = false
			}
			continue
		}
		out = append(out, l)
	}
	return strings.Join(out, "\n"), found
}

// Version returns the recorded version of a site folder, if the file has one.
func Version(text, folder string) string {
	for _, line := range strings.Split(text, "\n") {
		f := strings.Fields(line)
		if len(f) == 4 && f[0] == "#" && f[1] == "site" && f[2] == folder {
			return f[3]
		}
	}
	return ""
}
