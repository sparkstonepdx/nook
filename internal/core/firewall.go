package core

import (
	"fmt"
	"os"
	"os/exec"
	"os/user"
	"sort"
	"strings"

	"github.com/sparkstonepdx/nook/internal/config"
)

// FirewallRules is the nftables table that keeps apps off each other's ports: on this box, a connection to a
// port in the app range is allowed only from root, Caddy, or the app that owns the port. It loads in one
// transaction (create, delete, recreate), so it's never half applied and can be reloaded any time.
func FirewallRules(s config.Settings) string {
	var elems []string
	for _, p := range readPorts() {
		if u, err := LookupApp(p.App); err == nil {
			elems = append(elems, fmt.Sprintf("%d . %d", p.Port, u.UID))
		}
	}
	elems = append(elems, bindingFirewall()...)
	sort.Strings(elems)
	trusted := []string{"0"}
	if u, err := user.Lookup("caddy"); err == nil {
		trusted = append(trusted, u.Uid)
	}
	set := "\tset owner {\n\t\ttype inet_service . uid\n"
	if len(elems) > 0 {
		set += "\t\telements = { " + strings.Join(elems, ", ") + " }\n"
	}
	set += "\t}\n"
	r := fmt.Sprintf("%d-%d", s.PortMin, s.PortMax)
	return "# generated by nook: do not edit\ntable inet nook\ndelete table inet nook\ntable inet nook {\n" + set +
		"\tchain out {\n\t\ttype filter hook output priority 0; policy accept;\n" +
		"\t\toif \"lo\" meta skuid { " + strings.Join(trusted, ", ") + " } accept\n" +
		"\t\toif \"lo\" tcp dport " + r + " tcp dport . meta skuid @owner accept\n" +
		"\t\toif \"lo\" tcp dport " + r + " drop\n" +
		"\t\toif \"lo\" udp dport " + r + " drop\n" +
		"\t}\n}\n"
}

// Firewall writes and loads the rules. Without nft it says so and changes nothing.
func Firewall() error {
	nft, err := exec.LookPath("nft")
	if err != nil {
		return fmt.Errorf("nft isn't installed, so apps can reach each other's ports (apt install nftables)")
	}
	text := FirewallRules(config.Load())
	if err := config.WriteAtomic(config.FirewallFile, []byte(text), 0o600); err != nil {
		return err
	}
	if out, err := exec.Command(nft, "-f", config.FirewallFile).CombinedOutput(); err != nil {
		return fmt.Errorf("nft: %v: %s", err, strings.TrimSpace(string(out)))
	}
	return nil
}

func applyFirewall() {
	if err := Firewall(); err != nil {
		fmt.Fprintf(os.Stderr, "firewall: %v\n", err)
	}
}
