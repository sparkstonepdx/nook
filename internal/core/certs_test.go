func TestVerifyCloudflare(t *testing.T) {
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		tok := strings.TrimPrefix(r.Header.Get("Authorization"), "Bearer ")
		switch {
		case r.URL.Path == "/user/tokens/verify" && tok == "bad":
			w.Write([]byte(`{"success":false,"errors":[{"message":"Invalid API Token"}]}`))
		case r.URL.Path == "/user/tokens/verify":
			w.Write([]byte(`{"success":true,"result":{"status":"active"}}`))
		case r.URL.Path == "/zones" && tok == "good" && r.URL.Query().Get("name") == "example.com":
			w.Write([]byte(`{"success":true,"result":[{"id":"z1","name":"example.com"}]}`))
		default:
			w.Write([]byte(`{"success":true,"result":[]}`))
		}
	}))
	defer srv.Close()
	cloudflareAPI = srv.URL
	if err := verifyCloudflare("good", "example.com"); err != nil {
		t.Fatal(err)
	}
	if err := verifyCloudflare("good", "apps.example.com"); err != nil { // a sub grant finds its parent zone
		t.Fatal(err)
	}
	if err := verifyCloudflare("bad", "example.com"); err == nil || !strings.Contains(err.Error(), "Invalid API Token") {
		t.Fatalf("bad token: %v", err)
	}
	if err := verifyCloudflare("other", "example.com"); err == nil || !strings.Contains(err.Error(), "Edit zone DNS") {
		t.Fatalf("wrong zone: %v", err)
	}
}

func TestInstallCaddyBuild(t *testing.T) {
	dir := t.TempDir()
	// the installed Caddy: no plugin
	old := "#!/bin/sh\ncase \"$1\" in version) echo v2.6.2;; list-modules) echo http;; esac\n"
	os.WriteFile(filepath.Join(dir, "caddy"), []byte(old), 0o755)
	t.Setenv("PATH", dir+":"+os.Getenv("PATH"))
	var asked string
	build := "#!/bin/sh\ncase \"$1\" in version) echo v2.10.2;; list-modules) echo http; echo dns.providers.cloudflare;; validate) exit 0;; esac\n"
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		asked = r.URL.RawQuery
		if r.URL.Query().Get("p") == "missing" {
			w.Write([]byte("#!/bin/sh\necho v2.10.2\n")) // a build without the module
			return
		}
		w.Write([]byte(build))
	}))
	defer srv.Close()
	caddyDownload = srv.URL
	h := New(io.Discard)

	if err := h.installCaddyBuild([]string{"missing"}, "dns.providers.cloudflare"); err == nil || !strings.Contains(err.Error(), "doesn't list") {
		t.Fatalf("a build without the module was accepted: %v", err)
	}
	if b, _ := os.ReadFile(filepath.Join(dir, "caddy")); string(b) != old {
		t.Fatal("a refused build replaced caddy")
	}
	if err := h.installCaddyBuild([]string{"github.com/caddy-dns/cloudflare"}, "dns.providers.cloudflare"); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(asked, "p=github.com%2Fcaddy-dns%2Fcloudflare") || !strings.Contains(asked, "os=linux") {
		t.Fatalf("asked for %s", asked)
	}
	if b, _ := os.ReadFile(filepath.Join(dir, "caddy")); string(b) != build {
		t.Fatal("caddy wasn't replaced")
	}
	if b, _ := os.ReadFile(filepath.Join(dir, "caddy.nook-old")); string(b) != old {
		t.Fatal("the old caddy wasn't kept")
	}
	if left, _ := filepath.Glob(filepath.Join(dir, ".caddy-nook-*")); len(left) != 0 {
		t.Fatalf("temp files left: %v", left)
	}
}

func TestOwnCertUntilIssued(t *testing.T) {
	ex := []wildcard{{Domain: "example.com", Provider: "cloudflare", Env: "NOOK_DNS_1"}}
	if _, got, _ := underWildcard("blog.example.com", ex); got != "example.com" {
		t.Fatal("one level under isn't covered by the domain's wildcard")
	}
	if _, got, _ := underWildcard("a.b.example.com", ex); got != "b.example.com" {
		t.Fatalf("two levels under should need *.b.example.com, got %q", got)
	}
	for _, h := range []string{"example.com", "blogexample.com", "x.other.com"} {
		if _, _, ok := underWildcard(h, ex); ok {
			t.Errorf("%s shouldn't be under the wildcard", h)
		}
	}
	dir := t.TempDir()
	certsFile, caddyCertsDir = filepath.Join(dir, "certs.json"), filepath.Join(dir, "certs")
	os.WriteFile(certsFile, []byte(`{"wildcards":[{"domain":"example.com","provider":"cloudflare","env":"NOOK_DNS_1"}]}`), 0o600)
	// a Caddy that prefers wildcards
	bin := filepath.Join(dir, "bin")
	os.MkdirAll(bin, 0o755)
	os.WriteFile(filepath.Join(bin, "caddy"), []byte("#!/bin/sh\necho v2.10.2\n"), 0o755)
	t.Setenv("PATH", bin+":"+os.Getenv("PATH"))
	caddyVersionCache.mtime = time.Time{}

	own := OwnCert()
	if own == nil || !own("blog.example.com") || own("example.com") {
		t.Fatal("pending wildcard: subdomains should keep their own certificate")
	}
	before := wildcardState()
	// the wildcard is issued: a certificate in Caddy's store
	key, _ := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	tmpl := &x509.Certificate{SerialNumber: big.NewInt(1), NotBefore: time.Now().Add(-time.Hour), NotAfter: time.Now().Add(90 * 24 * time.Hour), DNSNames: []string{"*.example.com"}}
	der, _ := x509.CreateCertificate(rand.Reader, tmpl, tmpl, &key.PublicKey, key)
	d := filepath.Join(caddyCertsDir, "acme-v02.api.letsencrypt.org-directory", "wildcard_.example.com")
	os.MkdirAll(d, 0o755)
	os.WriteFile(filepath.Join(d, "wildcard_.example.com.crt"), pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der}), 0o644)
	if own := OwnCert(); own("blog.example.com") {
		t.Fatal("issued wildcard: hosts should use it")
	}
	if own := OwnCert(); !own("a.deep.example.com") {
		t.Fatal("a deeper host's nested wildcard isn't issued: it should keep its own certificate")
	}
	if wildcardState() == before {
		t.Fatal("the watcher wouldn't notice the wildcard was issued")
	}
	// Caddy before 2.10 has no force_automate
	os.WriteFile(filepath.Join(bin, "caddy"), []byte("#!/bin/sh\necho 2.6.2\n"), 0o755)
	os.Chtimes(filepath.Join(bin, "caddy"), time.Now(), time.Now().Add(time.Minute))
	os.RemoveAll(caddyCertsDir)
	if OwnCert() != nil {
		t.Fatal("old Caddy got force_automate")
	}
}

func TestNestedWildcards(t *testing.T) {
	ws := []wildcard{
		{Domain: "example.com", Provider: "cloudflare", Env: "NOOK_DNS_1"},
		{Domain: "apps.example.com", Provider: "cloudflare", Env: "NOOK_DNS_2"}, // its own, configured
	}
	hosts := []string{"blog.example.com", "a.b.example.com", "c.b.example.com", "a.c.example.com", "x.y.z.example.com", "one.apps.example.com", "two.deep.apps.example.com", "other.org", "example.com"}
	got := map[string]wildcard{}
	for _, n := range nestedWildcards(ws, hosts) {
		got[n.Domain] = n
	}
	want := map[string]string{"b.example.com": "NOOK_DNS_1", "c.example.com": "NOOK_DNS_1", "y.z.example.com": "NOOK_DNS_1", "deep.apps.example.com": "NOOK_DNS_2"}
	if len(got) != len(want) {
		t.Fatalf("got %v", got)
	}
	for d, env := range want {
		if got[d].Env != env || got[d].Parent == "" {
			t.Errorf("%s: %+v", d, got[d])
		}
	}
	// a.b. and c.b. share one; apps.example.com is configured, not nested; one level under it needs nothing new
	if _, ok := got["apps.example.com"]; ok {
		t.Error("a configured wildcard came back as nested")
	}
	tls := renderTLS(append(ws, nestedWildcards(ws, hosts)...))
	if !strings.Contains(tls, "*.b.example.com {\n\ttls {\n\t\tdns cloudflare {env.NOOK_DNS_1}") {
		t.Fatalf("nested wildcard not rendered with its parent's token:\n%s", tls)
	}
}

