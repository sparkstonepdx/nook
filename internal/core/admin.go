// AdminCaddy writes /etc/caddy/nook-dashboard.caddy: the dashboard at its address and (unless turned off) the IP.
func (h *Host) AdminCaddy() error {
	h.S = config.Load()
	d := config.LoadDashboard()
	var b strings.Builder
	b.WriteString("# generated by nook: do not edit\n")
	if d.Host != "" {
		fmt.Fprintf(&b, "%s {\n\treverse_proxy unix/%s\n}\n", d.Host, config.WebSocket)
	}
	if d.IPAccess && h.S.SSHHost != "" {
		fmt.Fprintf(&b, "https://%s:%s {\n\ttls internal\n\treverse_proxy unix/%s\n}\n", h.S.SSHHost, d.IPPort, config.WebSocket)
	}
	old, oldErr := os.ReadFile(config.AdminCaddy)
	if err := config.WriteAtomic(config.AdminCaddy, []byte(b.String()), 0o644); err != nil {
		return err
	}
	ensureImport(config.AdminCaddy)
	if out, err := Run("caddy", "validate", "--config", config.Caddyfile); err != nil {
		if oldErr == nil {
			config.WriteAtomic(config.AdminCaddy, old, 0o644)
		}
		return fmt.Errorf("Caddy config failed to validate; kept the previous one\n%s", lastLines(out, 5))
	}
	if string(old) != b.String() {
		systemctl("reload", "caddy")
	}
	if d.IPAccess {
		h.say("dashboard: https://%s:%s (self-signed certificate)", h.S.SSHHost, d.IPPort)
	}
	if d.Host != "" {
		h.say("dashboard: https://%s", d.Host)
	}
	return nil
}

func ensureImport(path string) {
	b, _ := os.ReadFile(config.Caddyfile)
	line := "import " + path
	for _, l := range strings.Split(string(b), "\n") {
		if strings.TrimSpace(l) == line {
			return
		}
	}
	config.WriteAtomic(config.Caddyfile, []byte(strings.TrimRight(string(b), "\n")+"\n\n"+line+"\n"), 0o644)
}

func (h *Host) ReloadCaddy() error {
	if out, err := Run("caddy", "validate", "--config", config.Caddyfile); err != nil {
		return fmt.Errorf("Caddy config doesn't validate:\n%s", lastLines(out, 8))
	}
	if err := systemctl("reload", "caddy"); err != nil {
		return err
	}
	h.say("reloaded Caddy")
	return nil
}

func (h *Host) SetDefaultDomain(d string) error {
	d = strings.ToLower(strings.TrimSpace(d))
	if !names.Host(d) {
		return fmt.Errorf("not a valid domain")
	}
	old := h.S.BaseDomain
	if d == old {
		return nil
	}
	unlock, err := Lock()
	if err != nil {
		return err
	}
	config.Set(config.ConfigFile, "BASE_DOMAIN", d)
	gl, _ := grants.Load(config.GrantsFile)
	for i, g := range gl {
		if g.Kind == "sub" && g.Name == old {
			gl[i].Name = d
		}
	}
	config.WriteAtomic(config.GrantsFile, []byte(gl.Text()), 0o600)
	unlock()
	h.S = config.Load()
	if err := h.AdminCaddy(); err != nil {
		return err
	}
	return h.SyncAll()
}

func (h *Host) SetDashboardHost(host string) error {
	host = strings.ToLower(strings.TrimSpace(host))
	if host != "" && !names.Host(host) {
		return fmt.Errorf("not a valid hostname")
	}
	if host != "" {
		for app, text := range otherCaddyFiles("") {
			live, red := caddyfile.Hosts(text)
			for _, l := range append(live, red...) {
				if l == host {
					return fmt.Errorf("%s is served by app %s. Remove that site or pick another name", host, app)
				}
			}
		}
	}
	config.Set(config.DashboardEnv, "DASHBOARD_HOST", host)
	return h.AdminCaddy()
}

func (h *Host) SetIPAccess(on bool) error {
	if !on && config.LoadDashboard().Host == "" {
		return fmt.Errorf("set a dashboard address first, or you'd lock yourself out")
	}
	v := "off"
	if on {
		v = "on"
	}
	config.Set(config.DashboardEnv, "DASHBOARD_IP_ACCESS", v)
	return h.AdminCaddy()
}

// SiteOp is restart / stop / start / remove for one site.
func (h *Host) SiteOp(app, site, op string) error {
	u, err := LookupApp(app)
	if err != nil {
		return err
	}
	if !names.Site(site) {
		return fmt.Errorf("invalid site name")
	}
	unit := UnitName(app, site)
	switch op {
	case "restart", "stop", "start":
		out, err := Run("systemctl", op, unit)
		h.say("systemctl %s %s %s", op, unit, strings.TrimSpace(out))
		return err
	case "remove":
		sites, err := openDirNoFollow(filepath.Join(u.Home, "sites"))
		if err != nil {
			return err
		}
		defer sites.close()
		if st, err := sites.lstat(site); err != nil || !isDir(st) {
			return fmt.Errorf("no such site")
		}
		// remove as the app user, so a swapped-in symlink can't point root somewhere else
		if _, err := u.AsApp(1<<16, "site", "rm", site); err != nil {
			return err
		}
		return h.Sync(app)
	}
	return fmt.Errorf("unknown operation")
}

type SiteInfo struct {
	Name     string `json:"name"`
	Host     string `json:"host"`
	Running  bool   `json:"running"`
	Live     bool   `json:"live"`
	Port     string `json:"port"`
	Active   string `json:"ActiveState,omitempty"`
	Sub      string `json:"SubState,omitempty"`
	PID      string `json:"MainPID,omitempty"`
	Memory   string `json:"MemoryCurrent,omitempty"`
	Restarts string `json:"NRestarts,omitempty"`
}

type AppInfo struct {
	Name      string     `json:"name"`
	Memory    string     `json:"memory"`
	MemoryMax string     `json:"memoryMax"`
	CPU       string     `json:"cpu"`
	Watcher   string     `json:"watcher"`
	Sites     []SiteInfo `json:"sites"`
	Redirects []string   `json:"redirects"`
	Grants    [][]string `json:"grants"`
}

func mb(v string) string {
	if n, err := strconv.ParseUint(v, 10, 64); err == nil {
		return strconv.FormatUint(n/1048576, 10) + "M"
	}
	return ""
}

// Overview is what the dashboard's Apps page shows.
func (h *Host) Overview() map[string]any {
	h.S = config.Load()
	gl, _ := grants.Load(config.GrantsFile)
	var apps []AppInfo
	for _, a := range Apps() {
		u, _ := LookupApp(a)
		text, _ := os.ReadFile(filepath.Join(config.CaddyAppsDir, a+".caddy"))
		live, red := caddyfile.Hosts(string(text))
		liveSet := map[string]bool{}
		for _, l := range live {
			liveSet[l] = true
		}
		slice := UnitProps("nook-"+a+".slice", "MemoryCurrent", "MemoryMax", "CPUQuotaPerSecUSec")
		watcher := UnitProps("nook-sync@"+a+".path", "ActiveState")["ActiveState"]
		if watcher == "" {
			watcher = "?"
		}
		info := AppInfo{Name: a, Memory: mb(slice["MemoryCurrent"]), MemoryMax: mb(slice["MemoryMax"]), CPU: slice["CPUQuotaPerSecUSec"], Watcher: watcher, Redirects: red, Sites: []SiteInfo{}, Grants: [][]string{}}
		if info.Redirects == nil {
			info.Redirects = []string{}
		}
		for _, g := range gl.For(a) {
			info.Grants = append(info.Grants, []string{g.App, g.Kind, g.Name})
		}
		if sites, err := openDirNoFollow(filepath.Join(u.Home, "sites")); err == nil {
			for _, s := range sites.names() {
				if strings.HasPrefix(s, ".") {
					continue
				}
				st, err := sites.lstat(s)
				if err != nil || !isDir(st) || !names.Site(s) {
					continue
				}
				si := SiteInfo{Name: s, Host: names.HostOf(s, h.S.BaseDomain)}
				si.Live = liveSet[si.Host]
				if run, err := sites.lstatIn(s, "run"); err == nil && isFile(run) && run.Mode&0o111 != 0 {
					si.Running = true
					p := UnitProps(UnitName(a, s), "ActiveState", "SubState", "MainPID", "MemoryCurrent", "NRestarts")
					si.Active, si.Sub, si.PID, si.Memory, si.Restarts = p["ActiveState"], p["SubState"], p["MainPID"], p["MemoryCurrent"], p["NRestarts"]
				}
				if port := PortOf(a, s); port > 0 {
					si.Port = strconv.Itoa(port)
				}
				info.Sites = append(info.Sites, si)
			}
			sites.close()
		}
		apps = append(apps, info)
	}
	if apps == nil {
		apps = []AppInfo{}
	}
	free, _ := Run("free", "-m")
	df, _ := Run("df", "-h", "/", "/srv")
	caddy := UnitProps("caddy.service", "ActiveState")["ActiveState"]
	if caddy == "" {
		caddy = "?"
	}
	return map[string]any{
		"baseDomain": h.S.BaseDomain,
		"apps":       apps,
		"system":     map[string]string{"free": free, "df": df, "caddy": caddy},
		"defaults":   map[string]string{"memory": h.S.MemoryMax, "cpu": h.S.CPUQuota, "tasks": h.S.TasksMax},
	}
}

// Domains is what the dashboard's Domains page shows.
func (h *Host) Domains() map[string]any {
	h.S = config.Load()
	d := config.LoadDashboard()
	gl, _ := grants.Load(config.GrantsFile)
	type rec struct {
		Type, Name, Value, Note string
	}
	var dns []map[string]string
	seen := map[string]bool{}
	add := func(name, note string) {
		if !seen[name] {
			seen[name] = true
			dns = append(dns, map[string]string{"type": "A", "name": name, "value": h.S.SSHHost, "note": note})
		}
	}
	gs := []map[string]string{}
	for _, g := range gl {
		gs = append(gs, map[string]string{"app": g.App, "kind": g.Kind, "name": g.Name})
		if g.Kind != "sub" {
			add(g.Name, "")
		}
		if g.Kind != "host" {
			add("*."+g.Name, "")
		}
	}
	if d.Host != "" {
		add(d.Host, "dashboard")
	}
	if dns == nil {
		dns = []map[string]string{}
	}
	apps := Apps()
	if apps == nil {
		apps = []string{}
	}
	return map[string]any{
		"baseDomain": h.S.BaseDomain, "ip": h.S.SSHHost, "apps": apps, "grants": gs, "dns": dns,
		"dashboardHost": d.Host, "ipAccess": d.IPAccess, "ipPort": d.IPPort,
	}
}

func SiteLogs(app, site string) (map[string]string, error) {
	if _, err := LookupApp(app); err != nil {
		return nil, err
	}
	if !names.Site(site) {
		return nil, fmt.Errorf("invalid site name")
	}
	status, _ := Run("systemctl", "status", "--no-pager", "-n", "0", UnitName(app, site))
	s := config.Load()
	return map[string]string{"host": names.HostOf(site, s.BaseDomain), "status": status, "log": Tail(filepath.Join(config.LogDir, app, site+".log"), 300)}, nil
}

func SyncLog(app string) (string, error) {
	if _, err := LookupApp(app); err != nil {
		return "", err
	}
	out, _ := Run("journalctl", "--no-pager", "-n", "200", "-u", "nook-sync@"+app+".service")
	return out, nil
}

