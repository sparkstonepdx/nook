#!/bin/bash
# One-time setup of the app host. Run as root on the Debian VPS, from inside this repo.
#   ./install.sh
#   BASE_DOMAIN=example.com SSH_HOST=1.2.3.4 ./install.sh
# Safe to re-run (keeps /etc/apps/config if it exists).
set -euo pipefail
cd "$(dirname "$0")"
[ "$(id -u)" = 0 ] || { echo "run as root"; exit 1; }
command -v caddy >/dev/null || { echo "install Caddy first (setup-server.sh does)"; exit 1; }

BASE_DOMAIN="${BASE_DOMAIN:-sparkstonepdx.com}"
SSH_HOST="${SSH_HOST:-$(hostname -I | awk '{print $1}')}"

mkdir -p /etc/apps/state /etc/caddy/apps /srv/apps
chmod 700 /etc/apps; chmod 711 /srv/apps    # app users can enter their own folder but not list the others
touch /etc/apps/ports; chmod 600 /etc/apps/ports
if [ ! -f /etc/apps/config ]; then
cat > /etc/apps/config <<EOF
BASE_DOMAIN=$BASE_DOMAIN
SSH_HOST=$SSH_HOST
APPS_DIR=/srv/apps
PORTS_FILE=/etc/apps/ports
STATE_DIR=/etc/apps/state
CADDY_APPS_DIR=/etc/caddy/apps
# running apps get ports from this range
PORT_MIN=20000
PORT_MAX=29999
# subdomains no app can claim
RESERVED_SUBDOMAINS="www mail admin"
# limits shared by everything one app runs
APP_MEMORY_MAX=256M
APP_CPU_QUOTA=50%
APP_TASKS_MAX=256
EOF
fi
chmod 600 /etc/apps/config
. /etc/apps/config

install -m 755 sbin/app-create sbin/app-sync sbin/app-delete sbin/app-dashboard-invite sbin/app-grant sbin/app-admin-caddy sbin/app-env /usr/local/sbin/
install -m 755 bin/app /usr/local/bin/
install -m 644 systemd/app-sync@.path systemd/app-sync@.service /etc/systemd/system/
install -m 644 logrotate/apps /etc/logrotate.d/apps
install -D -m 644 dashboard/server.mjs /usr/local/lib/app-host/dashboard/server.mjs
install -D -m 644 lib/env.mjs /usr/local/lib/app-host/env.mjs
rm -rf /usr/local/lib/app-host/dashboard/public && cp -r dashboard/public /usr/local/lib/app-host/dashboard/public
install -m 644 dashboard/app-dashboard.service /etc/systemd/system/
systemctl daemon-reload

# --- dashboard at admin.$BASE_DOMAIN ---
[ -f /etc/apps/dashboard.env ] || printf 'DASHBOARD_PORT=19999\n' > /etc/apps/dashboard.env
chmod 600 /etc/apps/dashboard.env
systemctl enable app-dashboard >/dev/null 2>&1; systemctl restart app-dashboard

# grants: which hostnames each app may use. Apps from before grants existed keep *.BASE_DOMAIN.
if [ ! -f /etc/apps/grants ]; then
  : > /etc/apps/grants
  for h in /srv/apps/*/; do [ -d "$h" ] && echo "$(basename "$h") sub $BASE_DOMAIN" >> /etc/apps/grants; done
fi
chmod 600 /etc/apps/grants

# --- Caddy's admin API: off the network. On localhost:2019 (the default) any app on this box could
# rewrite Caddy's config (take over every domain, serve Caddy's TLS keys). A unix socket in a caddy-only
# folder leaves it reachable by Caddy and root only; `systemctl reload caddy` finds it from the Caddyfile.
mkdir -p /etc/systemd/system/caddy.service.d
cat > /etc/systemd/system/caddy.service.d/app-host.conf <<'EOF'
[Service]
RuntimeDirectory=caddy
RuntimeDirectoryMode=0750
EOF
if ! grep -q 'admin unix//run/caddy/admin.sock' /etc/caddy/Caddyfile; then
  cp /etc/caddy/Caddyfile "/etc/caddy/Caddyfile.bak.$(date +%s)"
  if awk '!/^[[:space:]]*(#|$)/ {exit !/^[{][[:space:]]*$/}' /etc/caddy/Caddyfile; then
    # there's already a global options block: add the line inside it
    awk 'done!=1 && /^[{][[:space:]]*$/ {print; print "\tadmin unix//run/caddy/admin.sock"; done=1; next} {print}' /etc/caddy/Caddyfile > /etc/caddy/Caddyfile.new
  else
    { printf '{\n\tadmin unix//run/caddy/admin.sock\n}\n\n'; cat /etc/caddy/Caddyfile; } > /etc/caddy/Caddyfile.new
  fi
  mv /etc/caddy/Caddyfile.new /etc/caddy/Caddyfile
  CADDY_RESTART=1
fi

# --- catch-all: hostnames nothing serves get a plain 404 page on port 80 ---
# Debian's stock Caddyfile has a ":80 { root * /usr/share/caddy ... }" welcome page; it would clash, so it goes.
if grep -qE '^:80[[:space:]]*[{]' /etc/caddy/Caddyfile; then
  cp /etc/caddy/Caddyfile "/etc/caddy/Caddyfile.bak.$(date +%s)"
  awk '/^:80[[:space:]]*[{]/ {skip=1; next} skip && /^[}]/ {skip=0; next} !skip' /etc/caddy/Caddyfile > /etc/caddy/Caddyfile.new
  mv /etc/caddy/Caddyfile.new /etc/caddy/Caddyfile
  echo "Removed the default :80 site from /etc/caddy/Caddyfile (backup kept next to it)."
fi
mkdir -p /etc/caddy/catchall
[ -f /etc/caddy/catchall/index.html ] || install -m 644 caddy/catchall.html /etc/caddy/catchall/index.html   # yours to edit
cat > /etc/caddy/catchall.caddy <<'EOF'
# generated by app-host install.sh: unknown hostnames on port 80 get /etc/caddy/catchall/index.html (404).
# Known sites still redirect to HTTPS; edit the page, not this file.
:80 {
	error 404
	handle_errors {
		root * /etc/caddy/catchall
		rewrite * /index.html
		file_server
	}
}
EOF
grep -qxF 'import /etc/caddy/catchall.caddy' /etc/caddy/Caddyfile || printf '\nimport /etc/caddy/catchall.caddy\n' >> /etc/caddy/Caddyfile

# --- hardening for apps made before root-owned copies existed: lock app folders, then rebuild routes ---
mkdir -p /etc/apps/env /var/log/apps /var/lib/app-host/www; chmod 700 /etc/apps/env
for h in /srv/apps/*/; do [ -d "$h" ] && chmod 700 "$h" "$h/sites" 2>/dev/null; done

grep -qxF 'import /etc/caddy/apps/*.caddy' /etc/caddy/Caddyfile || printf '\nimport /etc/caddy/apps/*.caddy\n' >> /etc/caddy/Caddyfile
systemctl daemon-reload
if caddy validate --config /etc/caddy/Caddyfile >/dev/null 2>&1; then
  if [ "${CADDY_RESTART:-0}" = 1 ]; then systemctl restart caddy; else systemctl reload caddy; fi
else
  echo "Caddy config doesn't validate; fix /etc/caddy/Caddyfile (backups are next to it)"; caddy validate --config /etc/caddy/Caddyfile
fi
app-admin-caddy >/dev/null
app-sync --all >/dev/null || true
echo "App host installed (base domain $BASE_DOMAIN, SSH host $SSH_HOST)."
echo "Each app's subdomains need DNS: easiest is one wildcard record, *.$BASE_DOMAIN -> this server."
echo "Create an app with: app create NAME, or in the dashboard"
if [ ! -s /etc/apps/dashboard/users.json ] || [ "$(cat /etc/apps/dashboard/users.json)" = "{}" ]; then
  echo
  echo "Dashboard setup: open this to create your admin login (one use, expires in 24h)."
  echo "The certificate is self-signed, so accept the browser warning:"
  echo "  $(app-dashboard-invite)"
  echo "Then set the dashboard's address (e.g. admin.$BASE_DOMAIN) on its Domains page."
  echo "Lost it? Run: app invite"
fi
